// Optional artwork build. Run with Node and the sharp package after editing art.js.
// The site itself only loads the finished sprite sheets.
import {createRequire} from 'node:module';
import {writeFile} from 'node:fs/promises';
import {definitions} from './art.js';
const require=createRequire(import.meta.url);
const sharp=require(process.env.SHARP_MODULE || 'sharp');
const root=new URL('./',import.meta.url);
const scale=2, left=-175, top=-245, width=355, height=275;
const texture=await sharp(new URL('./paper.png',root).pathname).raw().toBuffer({resolveWithObject:true});
const sprites=[];
for(const match of definitions().matchAll(/<g id="(piece-[^"]+)">([\s\S]*?)<\/g>(?=<g id="piece-|$)/g)){
 const [,name,body]=match;
 const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="${width*scale}" height="${height*scale}" viewBox="${left} ${top} ${width} ${height}">${body}</svg>`;
 const {data,info}=await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const stride=info.width*4,stock=Buffer.alloc(data.length);
 let x0=info.width,y0=info.height,x1=0,y1=0;
 const lum=i=>(data[i]*.27+data[i+1]*.58+data[i+2]*.15)*data[i+3]/255;
 for(let y=5;y<info.height-5;y++)for(let x=5;x<info.width-5;x++){
  const i=y*stride+x*4,under=i-2*stride-8,edgeAlpha=data[under+3],alpha=data[i+3];
  if(!alpha&&!edgeAlpha)continue;
  x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);
  const t=((y%texture.info.height)*texture.info.width+(x%texture.info.width))*4;
  const pulp=(texture.data[t]>150?1:-1)*texture.data[t+3]*.23;
  // Directional relief along printed layers, warm beveled card core at the silhouette.
  const bevel=(lum(i+stride+4)-lum(under))*.22;
  const light=1.09-.19*x/info.width+.055*Math.sin(x*.036+y*.011)+.024*Math.sin(y*.071);
  const interior=(data[i-stride-4+3]/255);
  for(let c=0;c<3;c++){
   const base=alpha?data[i+c]:[105,75,47][c];
   const tone=(base-105)*1.11+105;
   const lit=tone*light+pulp+bevel+(1-interior)*(alpha/255)*[37,32,21][c];
   stock[i+c]=Math.max(0,Math.min(255,lit+[5,1,-6][c]));
  }
  stock[i+3]=Math.max(alpha,edgeAlpha);
 }
 const w=x1-x0+1,h=y1-y0+1;
 const sprite=await sharp(stock,{raw:info}).extract({left:x0,top:y0,width:w,height:h}).png().toBuffer();
 sprites.push({name,x:left+x0/scale,y:top+y0/scale,w,h,image:sprite});
 // Bake two penumbras into the shadow ink. A wide one softens its distant end,
 // while a narrow one preserves contact at the foot of the folding card.
 const pad=24,shadowWidth=w+2*pad,shadowHeight=h+2*pad;
 const source=await sharp(sprite).extractChannel(3).raw().toBuffer();
 const alpha=Buffer.alloc(shadowWidth*shadowHeight);
 for(let row=0;row<h;row++)source.copy(alpha,(row+pad)*shadowWidth+pad,row*w,(row+1)*w);
 const blur=radius=>sharp(alpha,{raw:{width:shadowWidth,height:shadowHeight,channels:1}}).blur(radius).greyscale().raw().toBuffer();
 const near=await blur(1.4),far=await blur(8),shade=Buffer.alloc(shadowWidth*shadowHeight*4);
 for(let i=0;i<alpha.length;i++){
  const spread=Math.max(0,Math.min(1,1-(Math.floor(i/shadowWidth)-pad)/h));
  shade.set([54,44,29,Math.round(near[i]*(1-spread)+far[i]*spread)],i*4);
 }
 sprites.push({name:name.replace('piece-','shade-'),x:left+(x0-pad)/scale,y:top+(y0-pad)/scale,w:shadowWidth,h:shadowHeight,image:await sharp(shade,{raw:{width:shadowWidth,height:shadowHeight,channels:4}}).png().toBuffer()});
}
sprites.sort((a,b)=>b.h-a.h);
const entries={},atlasWidth=2048,layers=[];
let x=2,y=2,row=0;
for(const s of sprites){
 if(x+s.w+2>atlasWidth){x=2;y+=row+4;row=0;}
 entries[s.name]=[s.x,s.y,s.w/scale,s.h/scale,x,y,s.w,s.h];
 layers.push({input:s.image,left:x,top:y});x+=s.w+4;row=Math.max(row,s.h);
}
const atlasHeight=y+row+2;
await sharp({create:{width:atlasWidth,height:atlasHeight,channels:4,background:'#00000000'}}).composite(layers).webp({quality:94,alphaQuality:100}).toFile(new URL('./cards.webp',root).pathname);
await writeFile(new URL('./cards.js',root),`// Generated by bake.mjs\nexport const sheetSize=[${atlasWidth},${atlasHeight}];\nexport const frames=${JSON.stringify(entries,null,0)};\n`);
console.log('Printed',sprites.length,'card designs.');
